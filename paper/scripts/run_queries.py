"""Step 4: run every Q-query in cypher/03_queries.cypher and save the results
as Markdown tables in output/query_results.md (handy for slides and the report)."""
import argparse, os, re
from neo4j import GraphDatabase

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def queries(path):
    text = open(path).read().split("// Visualization queries")[0]
    for block in re.split(r"\n(?=// Q\d+:)", text):
        m = re.match(r"// (Q\d+): (.*)\n", block)
        if m:
            body = "\n".join(l for l in block.splitlines() if not l.strip().startswith("//"))
            yield m.group(1), m.group(2).strip(), body.strip().rstrip(";")


def cell(v):
    if isinstance(v, list):
        v = ", ".join(map(str, v[:8])) + (f" (+{len(v) - 8})" if len(v) > 8 else "")
    return str(v).replace("|", "\\|") if v is not None else ""


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--uri", default="neo4j://localhost:7687")
    p.add_argument("--user", default="neo4j")
    p.add_argument("--password", default="")
    a = p.parse_args()
    auth = (a.user, a.password) if a.password else None
    out = ["# Query results\n", "Generated by scripts/run_queries.py from cypher/03_queries.cypher.\n"]
    with GraphDatabase.driver(a.uri, auth=auth) as driver, driver.session() as s:
        for qid, title, cypher in queries(os.path.join(ROOT, "cypher", "03_queries.cypher")):
            res = s.run(cypher)
            keys, recs = res.keys(), list(res)
            out.append(f"\n## {qid}: {title}\n")
            out.append("| " + " | ".join(keys) + " |")
            out.append("|" + "---|" * len(keys))
            out += ["| " + " | ".join(cell(r[k]) for k in keys) + " |" for r in recs]
            print(f"{qid}: {len(recs)} rows  ({title})")
    path = os.path.join(ROOT, "output", "query_results.md")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
